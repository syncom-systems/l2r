"""Deterministic evidence for arch-verify: Code Health deltas, displacement, gaming flags, impact floor.

Read-only. Compares a base git ref with the working tree (or --head ref). Stdlib only, so it runs in any
repository: `python3 arch_check.py ...`.
CodeScene is reached through its MCP server over stdio (ARCH_CS_MCP_CMD overrides the launch command,
default `npx -y @codescene/codehealth-mcp`). Every flag is evidence for a reviewer, not a verdict.
"""

