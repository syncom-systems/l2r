"""The evidence as a LikeC4 model (system `measured`), for views to include.

Each build unit is an element of `measured`, and each source unit an element
inside its build unit. Element ids are the unit id with every character that
LikeC4 does not allow replaced (`::` by `__`), so `my_crate::store::index` is
`measured.my_crate.my_crate__store__index`. Element kinds come from the
shared `spec.c4`; each unit kind names the element kind it is drawn as.
"""

from __future__ import annotations

import re

from .model import OBSERVED, Evidence

ELEMENT_KIND = {"rust_crate": "crate", "rust_module": "module"}


def c4_id(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name.replace("::", "__"))


def c4_path(evidence: Evidence, unit_id: str) -> str:
    owner = evidence.owner(unit_id)
    return f"measured.{c4_id(owner)}" + (f".{c4_id(unit_id)}" if unit_id != owner else "")


def pictured(evidence: Evidence) -> list[str]:
    """Every source unit of the scope, and the context source units a dependency touches."""
    inner = {k for k, u in evidence.units.items() if not u.is_build_unit}
    in_scope = {k for k in inner if "scope" in evidence.units[evidence.owner(k)].roles}
    ends = {x for d in evidence.of_kind(OBSERVED) for x in (d.source, d.target)}
    return sorted((ends & inner) | in_scope)


def model(evidence: Evidence) -> str:
    lines = ["// Generated by architecture-evidence; rewritten on every run. Do not edit.", "model {",
             "  measured = system 'Measured' {"]
    sources = pictured(evidence)
    for key in sorted(k for k, u in evidence.units.items() if u.is_build_unit):
        unit = evidence.units[key]
        lines.append(f"    {c4_id(key)} = {ELEMENT_KIND[unit.kind]} '{key}' {{")
        lines.append(f"      description '{', '.join(unit.roles)}'")
        lines += [f"      {c4_id(m)} = {ELEMENT_KIND[evidence.units[m].kind]} '{m}'"
                  for m in sources if evidence.owner(m) == key]
        lines.append("    }")
    for dep in evidence.dependencies:
        lines.append(f"    {c4_path(evidence, dep.source)} -> {c4_path(evidence, dep.target)} {{")
        lines.append(f"      metadata {{\n        evidence '{dep.evidence.replace(chr(39), '`')}'\n      }}\n    }}")
    lines += ["  }", "}", "", "views {", "  view measured_units {", "    title 'Build units (measured)'",
              "    include measured.*", "  }", "}", ""]
    return "\n".join(lines)
