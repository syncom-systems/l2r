//! Files shared by the whole generated crate: its Bazel package and crate root.

use l2r_model::Model;

use crate::plan::{Artifact, Ownership};
use crate::text;

/// Profile name recorded for crate-level files.
pub const PROFILE: &str = "crate-root/v0";

/// The Bazel package and crate root for the generated crate.
pub fn artifacts(model: &Model, root_module: &str, root_id: &str) -> Vec<Artifact> {
    vec![
        build_file(model, root_id),
        lib_rs(model, root_module, root_id),
    ]
}

fn build_file(model: &Model, root_id: &str) -> Artifact {
    let krate = &model.system.rust_crate;
    let content = format!(
        "# @generated by L2R ({PROFILE}). Do not edit: change the architecture model,\n\
         # then re-plan, re-approve and regenerate.\n\
         load(\"@rules_rust//rust:defs.bzl\", \"rust_library\", \"rust_test\")\n\
         \n\
         rust_library(\n    \
             name = \"{krate}\",\n    \
             srcs = glob([\"src/**/*.rs\"]),\n    \
             crate_root = \"src/lib.rs\",\n    \
             edition = \"2024\",\n    \
             visibility = [\"//visibility:public\"],\n\
         )\n\
         \n\
         rust_test(\n    \
             name = \"{krate}_test\",\n    \
             crate = \":{krate}\",\n    \
             edition = \"2024\",\n\
         )\n\
         \n\
         # Every file in this package, so that drift checks can compare it with the plan.\n\
         filegroup(\n    \
             name = \"l2r_files\",\n    \
             srcs = glob([\"**\"]),\n    \
             visibility = [\"//visibility:public\"],\n\
         )\n"
    );
    Artifact {
        path: "BUILD.bazel".into(),
        ownership: Ownership::Generated,
        profile: PROFILE.into(),
        purpose: "Bazel package building the generated crate and its contract tests".into(),
        components: vec![root_id.to_string()],
        lean: vec![],
        content,
    }
}

fn lib_rs(model: &Model, root_module: &str, root_id: &str) -> Artifact {
    let summary = format!(
        "{} — Rust scaffold generated by L2R from the architecture model `{}`.\n\
         \n\
         Module layout, types and contracts are fixed by the approved generation plan.\n\
         Behavior is implemented in the `imp.rs` and `routes.rs` files, which L2R\n\
         creates once and never overwrites.",
        model.system.name, model.system.id
    );
    let content = format!(
        "{}\n{}\n#![forbid(unsafe_code)]\n\npub mod {root_module};\n",
        text::generated_marker(PROFILE),
        text::inner_doc(&summary)
    );
    Artifact {
        path: "src/lib.rs".into(),
        ownership: Ownership::Generated,
        profile: PROFILE.into(),
        purpose: "Crate root".into(),
        components: vec![root_id.to_string()],
        lean: vec![],
        content,
    }
}
