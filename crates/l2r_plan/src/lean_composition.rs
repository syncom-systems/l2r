//! The derived Lean composition (`l2r.lean-composition/v0`).
//!
//! For every `composite/v0` component, this emits an `L2R.Async.Network`: the
//! approved structure (children in identifier order, each child's Lean state,
//! input, output, `init` and `step`, and each approved edge with its Lean
//! translation) wired to the generic semantics in `lean/L2R/Async.lean`.
//!
//! The text contains **no behaviour**: every behavioural fact is a reference to
//! the Lean specification's own declarations, already resolved against the
//! inventory by validation. Children and edges are ordered by exactly the
//! functions the `composite/v0` profile uses, so the network's scheduler
//! indices are the generated `System`'s. The output is deterministic, records
//! the digests of the model and inventory it was derived from, and is not part
//! of any generation plan, so deriving it never changes a plan digest.

use l2r_model::{Component, Model, digest, profiles as profile_ids};
use l2r_validate::Validated;

use crate::PlanError;
use crate::profiles::composite::{edges_within, is_machine};

/// Format identifier of the derived file.
pub const LEAN_COMPOSITION_FORMAT: &str = "l2r.lean-composition/v0";

/// The Lean module path of the derived file for `model`, relative to its root.
pub fn lean_composition_path(model: &Model) -> String {
    format!("L2RDerived/{}.lean", model.system.id)
}

/// Derives the Lean composition of every composite in `validated`.
pub fn lean_composition(validated: &Validated) -> Result<String, PlanError> {
    let model = validated.model();
    let mut out = format!(
        "-- @generated by L2R ({LEAN_COMPOSITION_FORMAT}). Do not edit: change the architecture model or the\n\
         -- Lean specification, then run `l2r lean-composition` again.\n\
         -- model: {}\n\
         -- inventory: {}\n\
         import L2R.Async\n",
        digest::digest_of(model),
        digest::digest_of(validated.inventory()),
    );
    for module in &validated.inventory().root_modules {
        out.push_str(&format!("import {module}\n"));
    }
    let mut composites: Vec<&Component> = model
        .components
        .iter()
        .filter(|c| c.profile == profile_ids::COMPOSITE_V0)
        .collect();
    composites.sort_by(|a, b| a.id.cmp(&b.id));
    if composites.is_empty() {
        return Err(PlanError("the model has no composite to derive".into()));
    }
    for composite in composites {
        out.push('\n');
        out.push_str(&network(model, composite)?);
    }
    Ok(out)
}

fn network(model: &Model, composite: &Component) -> Result<String, PlanError> {
    let children = model.children(&composite.id);
    if children.is_empty() {
        return Err(PlanError(format!(
            "composite `{}` has no children",
            composite.id
        )));
    }
    if let Some(nested) = children.iter().find(|c| !is_machine(c)) {
        return Err(PlanError(format!(
            "composite `{}` has the non-machine child `{}`; {LEAN_COMPOSITION_FORMAT} derives only \
             composites whose children are all machines",
            composite.id, nested.id
        )));
    }
    let n = children.len();
    let index = |id: &str| children.iter().position(|c| c.id == id);
    let edges = edges_within(model, composite);

    let mut out = format!(
        "/-!\n# Composite `{id}` ({name})\n\n\
         The structure the architecture model approves, as an `L2R.Async.Network`.\n\
         Children, by scheduler index (identifier order):\n\n",
        id = composite.id,
        name = composite.name,
    );
    for (i, child) in children.iter().enumerate() {
        out.push_str(&format!("- {i}: `{}`\n", child.id));
    }
    out.push_str("\nApproved edges, in routing order:\n\n");
    if edges.is_empty() {
        out.push_str("- none\n");
    }
    for edge in &edges {
        out.push_str(&format!(
            "- `{}`: `{}` → `{}` via `{}`\n",
            edge.id, edge.from, edge.to, edge.translation
        ));
    }
    out.push_str("-/\n");
    out.push_str(&format!(
        "namespace L2RDerived.«{}».«{}»\n\n",
        model.system.id, composite.id
    ));

    let behavior = |c: &Component| {
        c.behavior
            .clone()
            .ok_or_else(|| PlanError(format!("machine `{}` has no behavior", c.id)))
    };
    let behaviors = children
        .iter()
        .map(|c| behavior(c))
        .collect::<Result<Vec<_>, _>>()?;
    let unreachable = format!("  | ⟨_ + {n}, h⟩ => absurd h (by omega)\n");
    let by_child = |header: &str, item: &dyn Fn(usize) -> String| {
        let mut text = format!("{header}\n");
        for i in 0..n {
            text.push_str(&format!("  | ⟨{i}, _⟩ => {}\n", item(i)));
        }
        text.push_str(&unreachable);
        text.push('\n');
        text
    };
    out.push_str(&by_child(&format!("def State : Fin {n} → Type"), &|i| {
        behaviors[i].owned_state.clone()
    }));
    out.push_str(&by_child(&format!("def Input : Fin {n} → Type"), &|i| {
        behaviors[i].input.clone()
    }));
    out.push_str(&by_child(&format!("def Output : Fin {n} → Type"), &|i| {
        behaviors[i].output.clone()
    }));
    out.push_str(&by_child(
        &format!("def init : (c : Fin {n}) → State c"),
        &|i| behaviors[i].init.clone(),
    ));
    out.push_str(&by_child(
        &format!("def step : (c : Fin {n}) → State c → Input c → State c × Option (Output c)"),
        &|i| behaviors[i].step.clone(),
    ));

    let mut routes = Vec::with_capacity(n);
    for child in &children {
        let parts = edges
            .iter()
            .filter(|e| e.from == child.id)
            .map(|e| {
                let to = index(&e.to).ok_or_else(|| {
                    PlanError(format!(
                        "edge `{}` leaves composite `{}`",
                        e.id, composite.id
                    ))
                })?;
                Ok(format!(
                    "({} o).toList.map (fun i => ⟨⟨{to}, by decide⟩, i⟩)",
                    e.translation
                ))
            })
            .collect::<Result<Vec<String>, PlanError>>()?;
        routes.push(if parts.is_empty() {
            "fun _ => []".to_string()
        } else {
            format!("fun o =>\n    {}", parts.join(" ++\n    "))
        });
    }
    out.push_str(&by_child(
        &format!("def route : (c : Fin {n}) → Output c → List ((d : Fin {n}) × Input d)"),
        &|i| routes[i].clone(),
    ));
    out.push_str(&format!(
        "abbrev network : L2R.Async.Network := ⟨{n}, State, Input, Output, init, step, route⟩\n\n\
         end L2RDerived.«{}».«{}»\n",
        model.system.id, composite.id
    ));
    Ok(out)
}
