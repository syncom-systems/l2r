//! The derived Lean composition (`l2r.lean-composition/v0`).
//!
//! For every `composite/v0` component, this emits an `L2R.Async.Network`: the
//! approved structure (children in identifier order, each child's Lean state,
//! input, output, `init` and `step`, and each approved edge with its Lean
//! translation) wired to the generic semantics in `lean/L2R/Async.lean`.
//!
//! The text contains **no behaviour**: every behavioural fact is a reference to
//! the Lean specification's own declarations, already resolved against the
//! inventory by validation. Children and edges are ordered by exactly the
//! functions the `composite/v0` profile uses, so the network's scheduler
//! indices are the generated `System`'s. The output is deterministic, records
//! the digests of the model and inventory it was derived from, and is not part
//! of any generation plan, so deriving it never changes a plan digest.

use l2r_model::{Component, Kind, Model, Profile, Schema, digest};
use l2r_validate::Validated;

use crate::PlanError;
use crate::plan::GeneratorIdentity;
use crate::profiles::composite::is_machine;

/// Format identifier of the derived file for `composite/v0` composites.
pub const LEAN_COMPOSITION_FORMAT: &str = "l2r.lean-composition/v0";

/// Format identifier of the derived file for `composite/v1` composites: the
/// network additionally records mailbox capacities and typed ports, and is wired
/// to `l2r.async/v1`. `v0` output is unchanged.
pub const LEAN_COMPOSITION_FORMAT_V1: &str = "l2r.lean-composition/v1";

/// Identity of the `l2r.async/v1` semantics (`lean/L2R/Async1.lean`).
pub const SEMANTICS_VERSION_V1: &str = "l2r.async/v1";

const SEMANTICS_SOURCE_V1: &str = include_str!("../../../lean/L2R/Async1.lean");

/// Digest of the `l2r.async/v1` semantics source this build derives against.
pub fn semantics_digest_v1() -> String {
    digest::sha256(SEMANTICS_SOURCE_V1.as_bytes())
}

/// Identity of the semantics the derived network is wired to. It names the
/// version of `lean/L2R/Async.lean`; a behavioural change there is a new
/// version with a new file, never an edit under the same name.
pub const SEMANTICS_VERSION: &str = "l2r.async/v0";

/// The exact text of the semantics file the derived network imports. Its digest
/// is recorded in every derivation, so editing the semantics invalidates every
/// derived file (and the freshness test) until it is derived again and reviewed.
const SEMANTICS_SOURCE: &str = include_str!("../../../lean/L2R/Async.lean");

/// Digest of the semantics source this build of L2R derives against.
pub fn semantics_digest() -> String {
    digest::sha256(SEMANTICS_SOURCE.as_bytes())
}

/// The Lean module path of the derived file for `model`, relative to its root.
pub fn lean_composition_path(model: &Model) -> String {
    format!("L2RDerived/{}.lean", model.system.id)
}

/// Derives the Lean composition of every composite in `validated`.
///
/// `composite/v0` composites derive an `L2R.Async.Network`
/// (`l2r.lean-composition/v0`); a `composite/v1` derives an
/// `L2R.Async1.Network` with capacities and ports (`l2r.lean-composition/v1`).
/// A model uses one or the other: a `composite/v1` is always the root.
pub fn lean_composition(validated: &Validated) -> Result<String, PlanError> {
    match validated.schema() {
        Schema::V0 | Schema::V1 => {}
        Schema::V2 => {
            let flat = validated
                .flat()
                .ok_or_else(|| PlanError("a v2 model has no flat network".into()))?;
            return crate::lean_composition_v2::lean_composition_v2(validated, flat);
        }
    }
    let model = validated.model();
    let v1 = model
        .components
        .iter()
        .any(|c| validated.profile(&c.id) == Profile::CompositeV1);
    let (format, semantics, semantics_digest, import) = if v1 {
        (
            LEAN_COMPOSITION_FORMAT_V1,
            SEMANTICS_VERSION_V1,
            semantics_digest_v1(),
            "L2R.Async1",
        )
    } else {
        (
            LEAN_COMPOSITION_FORMAT,
            SEMANTICS_VERSION,
            semantics_digest(),
            "L2R.Async",
        )
    };
    let mut out = format!(
        "-- @generated by L2R ({format}). Do not edit: change the architecture model or the\n\
         -- Lean specification, then run `l2r lean-composition` again.\n\
         -- generator: {} {}\n\
         -- semantics: {semantics} {semantics_digest}\n\
         -- model: {}\n\
         -- inventory: {}\n\
         import {import}\n",
        GeneratorIdentity::current().name,
        GeneratorIdentity::current().version,
        digest::digest_of(model),
        digest::digest_of(validated.inventory()),
    );
    for module in &validated.inventory().root_modules {
        out.push_str(&format!("import {module}\n"));
    }
    let mut composites: Vec<&Component> = model
        .components
        .iter()
        .filter(|c| validated.profile(&c.id).kind() == Kind::Composite)
        .collect();
    composites.sort_by(|a, b| a.id.cmp(&b.id));
    if composites.is_empty() {
        return Err(PlanError("the model has no composite to derive".into()));
    }
    for composite in composites {
        out.push('\n');
        out.push_str(&network(model, composite, format)?);
    }
    Ok(out)
}

fn network(model: &Model, composite: &Component, format: &str) -> Result<String, PlanError> {
    let children = model.children(&composite.id);
    if children.is_empty() {
        return Err(PlanError(format!(
            "composite `{}` has no children",
            composite.id
        )));
    }
    if let Some(nested) = children.iter().find(|c| !is_machine(c)) {
        return Err(PlanError(format!(
            "composite `{}` has the non-machine child `{}`; {format} derives only \
             composites whose children are all machines",
            composite.id, nested.id
        )));
    }
    let n = children.len();
    let index = |id: &str| children.iter().position(|c| c.id == id);
    let edges = model.edges_within(&composite.id);

    let mut out = format!(
        "/-!\n# Composite `{id}` ({name})\n\n\
         The structure the architecture model approves, as an `L2R.Async.Network`.\n\
         Children, by scheduler index (identifier order):\n\n",
        id = composite.id,
        name = composite.name,
    );
    for (i, child) in children.iter().enumerate() {
        out.push_str(&format!("- {i}: `{}`\n", child.id));
    }
    out.push_str("\nApproved edges, in routing order:\n\n");
    if edges.is_empty() {
        out.push_str("- none\n");
    }
    for edge in &edges {
        out.push_str(&format!(
            "- `{}`: `{}` → `{}` via `{}`\n",
            edge.id, edge.from, edge.to, edge.translation
        ));
    }
    out.push_str("-/\n");
    out.push_str(&format!(
        "namespace L2RDerived.«{}».«{}»\n\n",
        model.system.id, composite.id
    ));

    let behavior = |c: &Component| {
        c.behavior
            .clone()
            .ok_or_else(|| PlanError(format!("machine `{}` has no behavior", c.id)))
    };
    let behaviors = children
        .iter()
        .map(|c| behavior(c))
        .collect::<Result<Vec<_>, _>>()?;
    let unreachable = format!("  | ⟨_ + {n}, h⟩ => absurd h (by omega)\n");
    let by_child = |header: &str, item: &dyn Fn(usize) -> String| {
        let mut text = format!("{header}\n");
        for i in 0..n {
            text.push_str(&format!("  | ⟨{i}, _⟩ => {}\n", item(i)));
        }
        text.push_str(&unreachable);
        text.push('\n');
        text
    };
    out.push_str(&by_child(&format!("def State : Fin {n} → Type"), &|i| {
        behaviors[i].owned_state.clone()
    }));
    out.push_str(&by_child(&format!("def Input : Fin {n} → Type"), &|i| {
        behaviors[i].input.clone()
    }));
    out.push_str(&by_child(&format!("def Output : Fin {n} → Type"), &|i| {
        behaviors[i].output.clone()
    }));
    out.push_str(&by_child(
        &format!("def init : (c : Fin {n}) → State c"),
        &|i| behaviors[i].init.clone(),
    ));
    out.push_str(&by_child(
        &format!("def step : (c : Fin {n}) → State c → Input c → State c × Option (Output c)"),
        &|i| behaviors[i].step.clone(),
    ));

    let mut routes = Vec::with_capacity(n);
    for child in &children {
        let parts = edges
            .iter()
            .filter(|e| e.from == child.id)
            .map(|e| {
                let to = index(&e.to).ok_or_else(|| {
                    PlanError(format!(
                        "edge `{}` leaves composite `{}`",
                        e.id, composite.id
                    ))
                })?;
                Ok(format!(
                    "({} o).toList.map (fun i => ⟨⟨{to}, by decide⟩, i⟩)",
                    e.translation
                ))
            })
            .collect::<Result<Vec<String>, PlanError>>()?;
        routes.push(if parts.is_empty() {
            "fun _ => []".to_string()
        } else {
            format!("fun o =>\n    {}", parts.join(" ++\n    "))
        });
    }
    out.push_str(&by_child(
        &format!("def route : (c : Fin {n}) → Output c → List ((d : Fin {n}) × Input d)"),
        &|i| routes[i].clone(),
    ));
    if composite.parsed_profile() == Some(Profile::CompositeV1) {
        out.push_str(&v1_tail(model, composite, &children, n));
    } else {
        out.push_str(&format!(
            "abbrev network : L2R.Async.Network := ⟨{n}, State, Input, Output, init, step, route⟩\n\n\
             end L2RDerived.«{}».«{}»\n",
            model.system.id, composite.id
        ));
    }
    Ok(out)
}

/// Capacities and ports of a `composite/v1`, and the `L2R.Async1.Network`.
fn v1_tail(model: &Model, composite: &Component, children: &[&Component], n: usize) -> String {
    let mut ports: Vec<&l2r_model::Port> = model
        .ports
        .iter()
        .filter(|p| p.composite == composite.id)
        .collect();
    ports.sort_by(|a, b| a.id.cmp(&b.id));
    let p = ports.len();
    let mut out = String::from("/-- Mailbox capacity of each child, from the model. -/\n");
    out.push_str(&format!("def cap : Fin {n} → Nat\n"));
    for (i, child) in children.iter().enumerate() {
        out.push_str(&format!(
            "  | ⟨{i}, _⟩ => {}\n",
            child.mailbox_capacity.unwrap_or(0)
        ));
    }
    out.push_str(&format!("  | ⟨_ + {n}, h⟩ => absurd h (by omega)\n\n"));
    let by_port = |header: &str, item: &dyn Fn(&l2r_model::Port) -> String| {
        let mut text = format!("{header}\n");
        for (i, port) in ports.iter().enumerate() {
            text.push_str(&format!("  | ⟨{i}, _⟩ => {}\n", item(port)));
        }
        text.push_str(&format!("  | ⟨_ + {p}, h⟩ => absurd h (by omega)\n\n"));
        text
    };
    out.push_str("/-- The typed ports, in identifier order: ");
    out.push_str(
        &ports
            .iter()
            .enumerate()
            .map(|(i, port)| format!("{i} = `{}`", port.id))
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str(". -/\n");
    out.push_str(&by_port(&format!("def Msg : Fin {p} → Type"), &|port| {
        port.message.clone()
    }));
    out.push_str(&by_port(
        &format!("def target : Fin {p} → Fin {n}"),
        &|port| {
            let idx = children
                .iter()
                .position(|c| c.id == port.target())
                .unwrap_or_default();
            format!("⟨{idx}, by decide⟩")
        },
    ));
    out.push_str(&by_port(
        &format!("def inject : (p : Fin {p}) → Msg p → Input (target p)"),
        &|port| port.translation_name().to_string(),
    ));
    out.push_str(&format!(
        "abbrev network : L2R.Async1.Network :=\n  ⟨{n}, State, Input, Output, init, step, route, cap, {p}, Msg, target, inject⟩\n\n\
         end L2RDerived.«{}».«{}»\n",
        model.system.id, composite.id
    ));
    out
}
